// Package apply implements the headless apply pipeline:
// answers.yaml -> docker-compose.yml + .env -> docker compose up -> wiring -> summary.
//
// WP1.1a skeleton: Resolve and Wire stages are implemented; Generate, ComposeUp,
// and WaitHealthy are wired in but Generate/WaitHealthy stub until later WPs.
package apply

import (
	"errors"
	"fmt"
	"os"
	"path/filepath"
	"runtime"
	"strings"

	"gopkg.in/yaml.v3"
)

// AnswersVersion is the only supported answers.yaml schema version.
const AnswersVersion = 1

// AllowedApps are the six v1 apps from templates/versions.yaml.
var AllowedApps = map[string]struct{}{
	"sonarr":      {},
	"radarr":      {},
	"prowlarr":    {},
	"qbittorrent": {},
	"jellyfin":    {},
	"seerr":       {},
}

// PresetApps maps each preset to its app list.
var PresetApps = map[string][]string{
	"movies": {"radarr", "prowlarr", "qbittorrent", "jellyfin", "seerr"},
	"family": {"sonarr", "radarr", "prowlarr", "qbittorrent", "jellyfin", "seerr"},
}

// Answers is the decoded answers.yaml v1 document.
type Answers struct {
	Version   int      `yaml:"version"`
	Preset    string   `yaml:"preset"`
	Apps      []string `yaml:"apps"`
	MediaRoot string   `yaml:"media_root"`
	HostOS    string   `yaml:"host_os"`
	Timezone  string   `yaml:"timezone"`
	PUID      *int     `yaml:"puid"`
	PGID      *int     `yaml:"pgid"`
	Extras    Extras   `yaml:"extras"`
}

// Extras holds optional feature flags. All must be false in v1.
type Extras struct {
	VPN       bool `yaml:"vpn"`
	Tailscale bool `yaml:"tailscale"`
}

// Plan is the resolved execution plan produced from Answers.
type Plan struct {
	Apps      []string
	MediaRoot string
	HostOS    string
	Timezone  string
	PUID      *int
	PGID      *int
	Extras    Extras
}

// LoadAnswers reads and strictly decodes an answers.yaml file. Unknown fields
// are rejected. Credentials are never stored in answers files; they are
// generated by internal/credentials and injected via .env at deploy time.
func LoadAnswers(path string) (*Answers, error) {
	data, err := os.ReadFile(path)
	if err != nil {
		return nil, fmt.Errorf("read answers file: %w", err)
	}
	var a Answers
	dec := yaml.NewDecoder(strings.NewReader(string(data)))
	dec.KnownFields(true)
	if err := dec.Decode(&a); err != nil {
		return nil, fmt.Errorf("decode answers: %w", err)
	}
	return &a, nil
}

// DefaultHostOS returns the canonical host_os value for the runtime OS.
func DefaultHostOS() string {
	switch runtime.GOOS {
	case "windows":
		return "windows"
	case "darwin":
		return "darwin"
	default:
		return "linux"
	}
}

// Validate checks the Answers against the v1 schema rules. It returns a
// validation error (exit-code-2 class) on any invalid input.
func Validate(a *Answers) error {
	var errs []error

	if a.Version != AnswersVersion {
		errs = append(errs, fmt.Errorf("version: expected %d, got %d", AnswersVersion, a.Version))
	}

	switch a.Preset {
	case "movies", "family", "custom":
	default:
		errs = append(errs, fmt.Errorf("preset: %q is not yet supported (allowed: movies, family, custom)", a.Preset))
	}

	if a.Preset == "custom" && len(a.Apps) == 0 {
		errs = append(errs, errors.New("apps: required when preset is custom"))
	}

	if a.HostOS == "" {
		a.HostOS = DefaultHostOS()
	}
	switch a.HostOS {
	case "linux", "windows", "darwin":
	default:
		errs = append(errs, fmt.Errorf("host_os: %q is not supported (allowed: linux, windows, darwin)", a.HostOS))
	}

	if a.MediaRoot == "" {
		errs = append(errs, errors.New("media_root: required"))
	} else if !isAbs(a.MediaRoot, a.HostOS) {
		errs = append(errs, fmt.Errorf("media_root: %q is not an absolute path for host_os %q", a.MediaRoot, a.HostOS))
	}

	if a.Timezone == "" {
		a.Timezone = "UTC"
	}

	if a.HostOS == "windows" {
		if a.PUID != nil {
			errs = append(errs, errors.New("puid: not supported on windows"))
		}
		if a.PGID != nil {
			errs = append(errs, errors.New("pgid: not supported on windows"))
		}
	}

	if a.Extras.VPN || a.Extras.Tailscale {
		errs = append(errs, errors.New("extras: vpn and tailscale must be false in v1"))
	}

	seen := make(map[string]struct{}, len(a.Apps))
	for _, app := range a.Apps {
		if _, ok := AllowedApps[app]; !ok {
			errs = append(errs, fmt.Errorf("apps: %q is not a known app", app))
			continue
		}
		if _, dup := seen[app]; dup {
			errs = append(errs, fmt.Errorf("apps: duplicate entry %q", app))
		}
		seen[app] = struct{}{}
	}

	return errors.Join(errs...)
}

// Resolve converts validated Answers into a Plan.
func Resolve(a *Answers) (*Plan, error) {
	if err := Validate(a); err != nil {
		return nil, err
	}

	apps := a.Apps
	if len(apps) == 0 {
		apps = PresetApps[a.Preset]
	}

	hostOS := a.HostOS
	if hostOS == "" {
		hostOS = DefaultHostOS()
	}

	timezone := a.Timezone
	if timezone == "" {
		timezone = "UTC"
	}

	return &Plan{
		Apps:      apps,
		MediaRoot: a.MediaRoot,
		HostOS:    hostOS,
		Timezone:  timezone,
		PUID:      a.PUID,
		PGID:      a.PGID,
		Extras:    a.Extras,
	}, nil
}

// FormatPlan renders a human-readable plan for --dry-run output.
func FormatPlan(p *Plan) string {
	var b strings.Builder
	b.WriteString("apps: ")
	for i, app := range p.Apps {
		if i > 0 {
			b.WriteString(", ")
		}
		b.WriteString(app)
	}
	b.WriteString("\nmedia_root: ")
	b.WriteString(p.MediaRoot)
	b.WriteString("\nhost_os: ")
	b.WriteString(p.HostOS)
	b.WriteString("\ntimezone: ")
	b.WriteString(p.Timezone)
	if p.PUID != nil {
		b.WriteString("\npuid: ")
		b.WriteString(fmt.Sprintf("%d", *p.PUID))
	}
	if p.PGID != nil {
		b.WriteString("\npgid: ")
		b.WriteString(fmt.Sprintf("%d", *p.PGID))
	}
	b.WriteString("\nextras: vpn=")
	b.WriteString(fmt.Sprintf("%v", p.Extras.VPN))
	b.WriteString(", tailscale=")
	b.WriteString(fmt.Sprintf("%v", p.Extras.Tailscale))
	b.WriteString("\nstages: resolve, generate(not implemented), compose-up, wait-healthy(not implemented), wire, summary\n")
	return b.String()
}

// isAbs reports whether p is an absolute path for the given host OS.
func isAbs(p, hostOS string) bool {
	switch hostOS {
	case "windows":
		// Accept C:\ or C:/ forms (case-insensitive drive letter).
		if len(p) >= 3 && p[1] == ':' && (p[2] == '\\' || p[2] == '/') {
			return true
		}
		// Also accept UNC-style \\server\share
		if strings.HasPrefix(p, "\\\\") || strings.HasPrefix(p, "//") {
			return true
		}
		return false
	case "linux", "darwin":
		return filepath.IsAbs(p)
	default:
		return filepath.IsAbs(p)
	}
}
